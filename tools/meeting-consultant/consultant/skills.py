"""Skill library: index SKILL.md files, retrieve relevant ones, write learned skills."""
import math
import re
from collections import Counter
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Iterable, List, Optional

STOP = set(
    "a an and are as at be by can for from has have how i if in into is it its of on or our so "
    "that the their them then there these this to use used using via was we what when where which "
    "who will with you your skill skills claude".split()
)


def tokens(text: str) -> List[str]:
    return [t for t in re.findall(r"[a-z0-9]+", text.lower()) if len(t) > 1 and t not in STOP]


def front_matter(text: str, fallback: str):
    fm = text.split("---", 2)[1] if text.startswith("---") and text.count("---") >= 2 else ""
    m = re.search(r"^name:\s*['\"]?([^'\"\n]+)", fm, re.M)
    name = m.group(1).strip() if m else fallback
    m = re.search(r"^description:\s*(?:[>|][-+]?)?\s*\n?((?:.*\n?)*?)(?=^[\w-]+:|\Z)", fm, re.M)
    desc = " ".join(m.group(1).split()).strip("'\"") if m else ""
    return name, desc


@dataclass
class SkillMeta:
    name: str
    description: str
    path: Path
    source: str  # "library" | "learned"

    @property
    def key(self) -> str:
        return str(self.path)


class SkillLibrary:
    def __init__(self, dirs: Iterable[str], learned_dir: str):
        self.dirs = [Path(d) for d in dirs]
        self.learned_dir = Path(learned_dir)
        self.skills: List[SkillMeta] = []
        self._df: Counter = Counter()
        self._tok: Dict[str, tuple] = {}

    def index(self) -> int:
        seen, skills = set(), []
        roots = [(d, "library") for d in self.dirs] + [(self.learned_dir, "learned")]
        for root, source in roots:
            if not root.exists():
                continue
            for path in sorted(root.rglob("SKILL.md")):
                if path in seen:
                    continue
                seen.add(path)
                try:
                    head = path.read_text(errors="ignore")[:4000]
                except OSError:
                    continue
                name, desc = front_matter(head, path.parent.name)
                skills.append(SkillMeta(name, desc, path, source))
        self.skills = skills
        self._df = Counter()
        self._tok = {}
        for s in skills:
            name_t, desc_t = set(tokens(s.name.replace("-", " "))), set(tokens(s.description))
            self._tok[s.key] = (name_t, desc_t)
            self._df.update(name_t | desc_t)
        return len(skills)

    def search(self, query: str, k: int = 40) -> List[SkillMeta]:
        if not self.skills:
            self.index()
        q = set(tokens(query))
        if not q:
            return []
        n = max(len(self.skills), 1)
        scored = []
        for s in self.skills:
            name_t, desc_t = self._tok[s.key]
            score = 0.0
            for t in q:
                idf = math.log(1 + n / (1 + self._df[t]))
                if t in name_t:
                    score += 3 * idf
                elif t in desc_t:
                    score += idf
            if score:
                if s.source == "learned":
                    score *= 1.5  # prefer what we learned in earlier meetings
                scored.append((score, s))
        scored.sort(key=lambda x: -x[0])
        return [s for _, s in scored[:k]]

    def by_name(self, name: str, among: Optional[List[SkillMeta]] = None) -> Optional[SkillMeta]:
        pool = among if among is not None else self.skills
        name = name.strip().lower()
        for s in pool:
            if s.name.lower() == name:
                return s
        return None

    @staticmethod
    def load(meta: SkillMeta, max_chars: int = 6000) -> str:
        text = meta.path.read_text(errors="ignore")
        return text if len(text) <= max_chars else text[:max_chars] + "\n…(truncated)"

    def learned(self) -> List[SkillMeta]:
        return [s for s in self.skills if s.source == "learned"]

    def write_learned(self, slug: str, name: str, description: str, body: str, meeting_ref: str) -> Path:
        slug = re.sub(r"[^a-z0-9-]+", "-", slug.lower()).strip("-")[:60] or "meeting-learnings"
        path = self.learned_dir / slug / "SKILL.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        desc = " ".join(description.split()).replace('"', "'")
        stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        path.write_text(
            f"---\nname: {name.strip()}\ndescription: \"{desc}\"\n---\n\n"
            f"<!-- Auto-generated by meeting-consultant (last updated {stamp}, from {meeting_ref}). "
            f"Review before promoting into the main skills library. -->\n\n{body.strip()}\n"
        )
        self.index()
        return path


async def select_skills(llm, model: str, library: "SkillLibrary", query: str, situation: str,
                        max_skills: int = 4) -> List[Dict[str, str]]:
    """Keyword-retrieve candidates from every indexed skill, then let Claude pick the few that fit."""
    candidates = library.search(query, 40)
    if not candidates:
        return []
    listing = "\n".join(f"- {s.name} [{s.source}]: {s.description[:220]}" for s in candidates)
    prompt = (f"You are choosing reference playbooks for an AI consultant.\n{situation}\n\n"
              f"Candidate skills:\n{listing}\n\n"
              f"Pick up to {max_skills} that would most improve the consultant's advice and questions here. "
              "Prefer frameworks and domain knowledge over tool automations. Reply with only JSON: "
              '{"skills": [{"name": "exact name from the list", "why": "one line"}]}')
    result = await llm.json("select_skills", model, prompt, max_tokens=600)
    picked, seen = [], set()
    for item in (result.get("skills") or [])[:max_skills]:
        meta = library.by_name(str(item.get("name", "")), candidates)
        if meta and meta.key not in seen:
            seen.add(meta.key)
            picked.append({"name": meta.name, "path": str(meta.path), "why": str(item.get("why", "")),
                           "source": meta.source})
    return picked


def load_skill_block(skills: List[Dict[str, str]]) -> str:
    parts = []
    for s in skills:
        path = Path(s["path"])
        if path.exists():
            body = SkillLibrary.load(SkillMeta(s["name"], "", path, s.get("source", "library")))
            parts.append(f'<skill name="{s["name"]}">\n{body}\n</skill>')
    return "\n\n".join(parts)
